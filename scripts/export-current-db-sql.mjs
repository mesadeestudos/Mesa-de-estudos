import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import 'dotenv/config';
import pg from 'pg';

const { Client } = pg;

const SCHEMAS = ['auth', 'concurso', 'planejamento'];
const OUT_PATH = path.resolve(process.cwd(), '..', 'docs', 'medb', 'medb.sql');

function qident(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function qname(schema, name) {
  return `${qident(schema)}.${qident(name)}`;
}

function roleLiteral(role) {
  return String(role).replaceAll("'", "''");
}

function stripSchemaQualification(sql) {
  return sql.replaceAll(`${qident('auth')}.`, '')
    .replaceAll(`${qident('concurso')}.`, '')
    .replaceAll(`${qident('planejamento')}.`, '');
}

async function query(client, text, params = []) {
  const result = await client.query(text, params);
  return result.rows;
}

async function main() {
  if (!process.env.DATABASE_URL) {
    throw new Error('DATABASE_URL não encontrada no .env.');
  }

  const client = new Client({ connectionString: process.env.DATABASE_URL });
  await client.connect();

  const databaseName = new URL(process.env.DATABASE_URL).pathname.replace(/^\//, '') || 'medb';

  const tables = await query(client, `
    SELECT table_schema, table_name
    FROM information_schema.tables
    WHERE table_schema = ANY($1)
      AND table_type = 'BASE TABLE'
    ORDER BY table_schema, table_name
  `, [SCHEMAS]);

  const lines = [
    '-- ======================================================',
    '-- MEDB - estrutura atual do banco',
    `-- Gerado em ${new Date().toISOString()} a partir do banco PostgreSQL configurado em DATABASE_URL.`,
    '-- Este arquivo contém DDL de schemas, tabelas, constraints, índices e permissões principais.',
    '-- Dados transacionais/cadastrais não são exportados aqui.',
    '-- ======================================================',
    '',
    '-- Executar conectado em um banco administrativo, se o banco ainda não existir:',
    `-- CREATE DATABASE ${qident(databaseName)};`,
    '',
    '-- Roles/senhas não são recuperáveis via catálogo do PostgreSQL.',
    '-- Ajuste as senhas conforme o ambiente antes de executar em uma instalação nova.',
    "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'me_dba') THEN CREATE ROLE me_dba LOGIN CREATEROLE PASSWORD 'troque_esta_senha'; END IF; END $$;",
    "DO $$ BEGIN IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'me_app') THEN CREATE ROLE me_app LOGIN PASSWORD 'troque_esta_senha'; END IF; END $$;",
    '',
    '-- Executar conectado no banco da aplicação.',
    '',
    '-- ======================================================',
    '-- SCHEMAS',
    '-- ======================================================',
    '',
  ];

  for (const schema of SCHEMAS) {
    lines.push(`CREATE SCHEMA IF NOT EXISTS ${qident(schema)};`);
  }

  lines.push('');

  for (const table of tables) {
    const { table_schema: schema, table_name: tableName } = table;
    const columns = await query(client, `
      SELECT
        a.attname AS column_name,
        format_type(a.atttypid, a.atttypmod) AS data_type,
        a.attnotnull AS not_null,
        a.attidentity AS identity_type,
        a.attgenerated AS generated_type,
        pg_get_expr(ad.adbin, ad.adrelid) AS column_default
      FROM pg_attribute a
      JOIN pg_class c ON c.oid = a.attrelid
      JOIN pg_namespace n ON n.oid = c.relnamespace
      LEFT JOIN pg_attrdef ad ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
      WHERE n.nspname = $1
        AND c.relname = $2
        AND a.attnum > 0
        AND NOT a.attisdropped
      ORDER BY a.attnum
    `, [schema, tableName]);

    lines.push('-- ======================================================');
    lines.push(`-- ${schema}.${tableName}`);
    lines.push('-- ======================================================');
    lines.push(`CREATE TABLE IF NOT EXISTS ${qname(schema, tableName)} (`);

    const columnSql = columns.map((column) => {
      const parts = [`    ${qident(column.column_name)}`, column.data_type];
      if (column.identity_type === 'a') parts.push('GENERATED ALWAYS AS IDENTITY');
      if (column.identity_type === 'd') parts.push('GENERATED BY DEFAULT AS IDENTITY');
      if (column.generated_type === 's') parts.push(`GENERATED ALWAYS AS (${column.column_default}) STORED`);
      if (column.column_default && !column.identity_type && !column.generated_type) parts.push(`DEFAULT ${column.column_default}`);
      if (column.not_null) parts.push('NOT NULL');
      return parts.join(' ');
    });

    lines.push(columnSql.join(',\n'));
    lines.push(');');
    lines.push('');
  }

  const constraints = await query(client, `
    SELECT
      n.nspname AS schema_name,
      c.relname AS table_name,
      con.conname AS constraint_name,
      con.contype,
      pg_get_constraintdef(con.oid, true) AS definition
    FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = ANY($1)
    ORDER BY
      CASE con.contype
        WHEN 'p' THEN 1
        WHEN 'u' THEN 2
        WHEN 'c' THEN 3
        WHEN 'f' THEN 4
        ELSE 5
      END,
      n.nspname,
      c.relname,
      con.conname
  `, [SCHEMAS]);

  lines.push('-- ======================================================');
  lines.push('-- CONSTRAINTS');
  lines.push('-- ======================================================');
  lines.push('');

  for (const constraint of constraints) {
    lines.push(
      `ALTER TABLE ${qname(constraint.schema_name, constraint.table_name)} ` +
      `ADD CONSTRAINT ${qident(constraint.constraint_name)} ${stripSchemaQualification(constraint.definition)};`
    );
  }

  lines.push('');

  const indexes = await query(client, `
    SELECT schemaname, tablename, indexname, indexdef
    FROM pg_indexes
    WHERE schemaname = ANY($1)
      AND indexname NOT IN (
        SELECT conname
        FROM pg_constraint con
        JOIN pg_class c ON c.oid = con.conrelid
        JOIN pg_namespace n ON n.oid = c.relnamespace
        WHERE n.nspname = ANY($1)
      )
    ORDER BY schemaname, tablename, indexname
  `, [SCHEMAS]);

  lines.push('-- ======================================================');
  lines.push('-- ÍNDICES');
  lines.push('-- ======================================================');
  lines.push('');

  for (const index of indexes) {
    lines.push(`${index.indexdef.replace(/^CREATE INDEX /, 'CREATE INDEX IF NOT EXISTS ')};`);
  }

  lines.push('');

  const grants = await query(client, `
    SELECT table_schema, table_name, grantee, privilege_type
    FROM information_schema.role_table_grants
    WHERE table_schema = ANY($1)
      AND grantee IN ('me_app', 'me_dba')
    ORDER BY table_schema, table_name, grantee, privilege_type
  `, [SCHEMAS]);

  const groupedGrants = new Map();
  for (const grant of grants) {
    const key = `${grant.table_schema}.${grant.table_name}.${grant.grantee}`;
    if (!groupedGrants.has(key)) groupedGrants.set(key, { ...grant, privileges: [] });
    groupedGrants.get(key).privileges.push(grant.privilege_type);
  }

  lines.push('-- ======================================================');
  lines.push('-- PERMISSÕES');
  lines.push('-- ======================================================');
  lines.push('');
  lines.push(`GRANT CONNECT ON DATABASE ${qident(databaseName)} TO me_app;`);
  lines.push(`GRANT USAGE ON SCHEMA ${SCHEMAS.map(qident).join(', ')} TO me_app;`);

  for (const grant of groupedGrants.values()) {
    lines.push(
      `GRANT ${grant.privileges.join(', ')} ON TABLE ${qname(grant.table_schema, grant.table_name)} TO ${qident(grant.grantee)};`
    );
  }

  lines.push('');
  lines.push('-- Garante que o me_app tenha acesso a futuras tabelas criadas nos schemas da aplicação.');
  for (const schema of SCHEMAS) {
    lines.push(`ALTER DEFAULT PRIVILEGES IN SCHEMA ${qident(schema)} GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO me_app;`);
  }
  lines.push('');

  fs.mkdirSync(path.dirname(OUT_PATH), { recursive: true });
  fs.writeFileSync(OUT_PATH, `${lines.join('\n')}\n`, 'utf8');
  await client.end();

  console.log(JSON.stringify({
    out: OUT_PATH,
    tables: tables.length,
    constraints: constraints.length,
    indexes: indexes.length,
  }, null, 2));
}

main().catch(async (error) => {
  console.error(error);
  process.exit(1);
});
